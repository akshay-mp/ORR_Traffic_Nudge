function makeDemoJourney(params: {
  id: string;
  userId: string;
  dateIst: string;
  direction: 'HOME_TO_WORK' | 'WORK_TO_HOME';
  transportMode: 'BIKE' | 'CAR' | 'BMTC';
  originLabel: string;
  destinationLabel: string;
  depHhmm: string;
  selPredDurMin: number;
  depPredDurMin: number;
  actualArrHhmm: string | null;
  changedPlanOrRoute: boolean;
  usefulRating: 'YES' | 'SOMEWHAT' | 'NO' | null;
  feedbackNote?: string;
}): JourneyRecord {
  const {
    id,
    userId,
    dateIst,
    direction,
    transportMode,
    originLabel,
    destinationLabel,
    depHhmm,
    selPredDurMin,
    depPredDurMin,
    actualArrHhmm,
    changedPlanOrRoute,
    usefulRating,
    feedbackNote,
  } = params;

  const [depH, depM] = depHhmm.split(':').map(Number);
  const depTotalMin = depH * 60 + depM;
  const selArrTotalMin = depTotalMin + selPredDurMin;
  const depArrTotalMin = depTotalMin + depPredDurMin;

  const fmtHhmm = (m: number) =>
    `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;

  const selArrHhmm = fmtHhmm(selArrTotalMin);
  const depArrHhmm = fmtHhmm(depArrTotalMin);

  const selectedEstimate: ImmutableEstimateSnapshot = {
    snapshotType: 'SELECTED_OPTION',
    optionId: `opt_demo_${id}`,
    departureTimeIst: depHhmm,
    predictedDurationMin: selPredDurMin,
    predictedArrivalIso: new Date(`${dateIst}T${selArrHhmm}:00+05:30`).toISOString(),
    predictedArrivalTimeIst: selArrHhmm,
    issuedAtIso: new Date(`${dateIst}T${depHhmm}:00+05:30`).toISOString(),
    issuedAtIst: `${depHhmm}:00 IST`,
    estimateBasis: transportMode === 'BMTC' ? 'TIMETABLE' : 'FUTURE_FORECAST',
    dataSource: 'ORR Pulse Synthetic Demo Engine (Labeled Demo)',
    environment: 'DEMO',
    userSafetyBufferMin: 5,
  };

  const departureEstimate: ImmutableEstimateSnapshot = {
    snapshotType: 'AT_DEPARTURE',
    optionId: `opt_demo_${id}`,
    departureTimeIst: depHhmm,
    predictedDurationMin: depPredDurMin,
    predictedArrivalIso: new Date(`${dateIst}T${depArrHhmm}:00+05:30`).toISOString(),
    predictedArrivalTimeIst: depArrHhmm,
    issuedAtIso: new Date(`${dateIst}T${depHhmm}:00+05:30`).toISOString(),
    issuedAtIst: `${depHhmm}:00 IST`,
    estimateBasis: transportMode === 'BMTC' ? 'TIMETABLE' : 'CURRENT_TRAFFIC',
    dataSource: 'ORR Pulse Synthetic Demo Engine (Labeled Demo)',
    environment: 'DEMO',
    userSafetyBufferMin: 5,
  };

  const actualDepartureIso = new Date(`${dateIst}T${depHhmm}:00+05:30`).toISOString();
  const actualArrivalIso = actualArrHhmm
    ? new Date(`${dateIst}T${actualArrHhmm}:00+05:30`).toISOString()
    : null;

  return {
    id,
    userId,
    dateIst,
    direction,
    transportMode,
    environment: 'DEMO',
    originLabel,
    destinationLabel,
    selectedEstimate,
    departureEstimate,
    actualDepartureIso,
    actualDepartureTimeIst: depHhmm,
    actualArrivalIso,
    actualArrivalTimeIst: actualArrHhmm,
    changedPlanOrRoute,
    usefulRating,
    feedbackNote,
    correctedAtIso: null,
    correctionHistoryCount: 0,
    metrics: computeJourneyMetrics(
      selectedEstimate,
      departureEstimate,
      actualDepartureIso,
      actualArrivalIso
    ),
  };
}

